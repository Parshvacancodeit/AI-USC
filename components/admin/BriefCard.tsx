"use client";
// P3 Dispatch Copilot: Today's brief / Weekly report for USG on the /admin Overview.
import { ClipboardCopy, FileText, Loader2, Sparkles } from "lucide-react";
import { useState } from "react";
import { adminPost } from "@/lib/admin";

type Brief = { headline: string; bullets: string[]; actions: string[]; ai: boolean };

export default function BriefCard() {
  const [win, setWin] = useState<"today" | "week" | null>(null);
  const [brief, setBrief] = useState<Brief | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);

  async function load(w: "today" | "week") {
    setWin(w);
    setBusy(true);
    setErr(null);
    setBrief(null);
    try {
      setBrief(await adminPost<Brief>("/api/admin/brief", { window: w }));
    } catch (e) {
      setErr((e as Error).message);
    } finally {
      setBusy(false);
    }
  }
  const text = brief ? [brief.headline, "", ...brief.bullets.map((b) => `• ${b}`), ...(brief.actions.length ? ["", "Next steps:", ...brief.actions.map((a) => `• ${a}`)] : [])].join("\n") : "";

  return (
    <section className="overflow-hidden rounded-xl border hairline bg-surface">
      <div className="flex flex-wrap items-center gap-2 border-b hairline px-3 py-2.5">
        <p className="flex flex-1 items-center gap-1.5 text-sm font-bold">
          <Sparkles size={14} className="text-accent" /> Copilot brief
        </p>
        {(["today", "week"] as const).map((w) => (
          <button key={w} onClick={() => load(w)} disabled={busy} className={`flex h-8 items-center gap-1.5 rounded-lg px-3 text-xs font-semibold disabled:opacity-50 ${win === w ? "bg-cardinal text-white" : "bg-surface-2"}`}>
            <FileText size={13} /> {w === "today" ? "Today's brief" : "Weekly report for USG"}
          </button>
        ))}
      </div>
      {busy && (
        <div className="space-y-2 p-3">
          <div className="shimmer h-4 w-3/4 rounded" />
          <div className="shimmer h-3 w-full rounded" />
          <div className="shimmer h-3 w-5/6 rounded" />
          <p className="flex items-center gap-1.5 text-xs text-muted">
            <Loader2 size={12} className="animate-spin" /> Reading live data…
          </p>
        </div>
      )}
      {err && <p className="p-3 text-sm text-open">Couldn&apos;t build the brief: {err}</p>}
      {brief && (
        <div className="space-y-2 p-3 text-sm">
          <p className="font-bold">{brief.headline}</p>
          <ul className="list-disc space-y-1 pl-5">
            {brief.bullets.map((b) => (
              <li key={b}>{b}</li>
            ))}
          </ul>
          {brief.actions.length > 0 && (
            <>
              <p className="pt-1 text-xs font-semibold uppercase tracking-wider text-muted">Next steps</p>
              <ul className="list-disc space-y-1 pl-5">
                {brief.actions.map((a) => (
                  <li key={a}>{a}</li>
                ))}
              </ul>
            </>
          )}
          <div className="flex items-center gap-2 border-t hairline pt-2">
            <p className="flex-1 text-xs text-muted">{brief.ai ? "Generated by AI from live data" : "Built from live data (AI unavailable)"}</p>
            <button
              onClick={() => {
                navigator.clipboard?.writeText(text);
                setCopied(true);
                setTimeout(() => setCopied(false), 1500);
              }}
              className="flex h-8 items-center gap-1 rounded-lg bg-surface-2 px-2.5 text-xs font-semibold"
            >
              <ClipboardCopy size={12} /> {copied ? "Copied" : "Copy"}
            </button>
          </div>
        </div>
      )}
    </section>
  );
}
